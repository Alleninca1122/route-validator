/**
 * 交付档位说明（服务模式，框架 v2.3）——附加在评审请求后，指导 recommendation 字段的填写。
 * 两档判定标准完全相同；区别只在交付深度。
 */
export function tierInstruction(tier: 'verdict' | 'verdict_plus'): string {
  if (tier === 'verdict') {
    return `## 交付档位：A 档（仅判定）
本次只判定路线可不可行：输出五关判决、注意项汇总与一句话重设计方向（写入 next_steps）。
JSON 中的 "recommendation" 字段必须为 null，不要搜索或生成替代路线。`;
  }
  return `## 交付档位：B 档（判定＋推荐）
在完成与 A 档完全相同的判定之后，再主动为客户找更好的路线，并填写 JSON 的 "recommendation" 字段：
- 若原路线结论为"候选"（五关全过）：无需替代，填 {"found": false, "source": null, "summary": "原路线已五关全过，无需替代路线；优化空间见下一步。", "route_description": "", "gates": []}。
- 若原路线被淘汰或止于第 5 关（实验室可行）：按以下顺序找替代——
  ① 若客户输入中包含多条候选路线/路线树，先按同一五关标准把它们全部评审、按存活情况重排，取存活者中最好的一条（source 填 "rerank"）；
  ② 否则给原路线打最小补丁：只动死因那一处（换试剂、调顺序、补保护），其余原样（source 填 "patch"）；
  ③ 补丁也不可行时，才另行设计一条整条替代路线（source 填 "generated"）。
- 有合适路线才推荐：推荐路线必须以同一五关标准自审通过（五关全过，或至少不死于第 1–4 关），并把它的五关记录填入 recommendation.gates（格式与主 gates 相同）；summary 写一句话推荐要点，route_description 概述推荐路线的关键步骤。推荐路线与原路线是两回事，不得混淆，也绝不许对推荐路线放水。
- 确实找不到合适路线时：填 {"found": false, "source": null, "summary": "如实说明为何没有可推荐的替代路线", "route_description": "", "gates": []}，并在 next_steps 中给出重设计方向。绝不为交付硬凑一条路线。`;
}
